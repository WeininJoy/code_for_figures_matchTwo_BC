    plot_class_on_axes(axes, filename1, color='blue', label='conventional CMB spectrum')
    plot_class_on_axes(axes, filename2, color='red',  label='fluctuating PPS (this work)')

    # --- Formatting ---
    ylabels = [
        r'$\mathcal{D}_\ell^{TT}\:[\mu\mathrm{K}^2]$',
        # r'$\mathcal{D}_\ell^{EE}\:[\mu\mathrm{K}^2]$',
        # r'$\mathcal{D}_\ell^{TE}\:[\mu\mathrm{K}^2]$',
        # r'$10^7\,[\ell(\ell+1)]^2\,C_\ell^{\phi\phi}\,/\,(2\pi)$',
    ]
    def autoscale_y(ax, margin=0.05):
        """Rescale y to fit all plotted data within the current x limits."""
        xmin, xmax = ax.get_xlim()
        ymin, ymax = np.inf, -np.inf
        for line in ax.lines:
            x, y = np.asarray(line.get_xdata()), np.asarray(line.get_ydata())
            mask = (x >= xmin) & (x <= xmax)
            if mask.any():
                ymin = min(ymin, np.nanmin(y[mask]))
                ymax = max(ymax, np.nanmax(y[mask]))
        for coll in ax.collections:   # errorbar markers/caps
            offs = coll.get_offsets()
            if len(offs):
                x, y = offs[:, 0], offs[:, 1]
                mask = (x >= xmin) & (x <= xmax)
                if mask.any():
                    ymin = min(ymin, np.nanmin(y[mask]))
                    ymax = max(ymax, np.nanmax(y[mask]))
        if np.isfinite(ymin) and np.isfinite(ymax):
            span = ymax - ymin
            ax.set_ylim(ymin - margin * span, ymax + margin * span)

    for ax, ylabel in zip(axes, ylabels):
        ax.set_xscale('log')
        ax.grid(True, alpha=0.3)
        ax.set_ylabel(ylabel, fontsize=13)
        ax.tick_params(axis='both', which='major', labelsize=13)
        ax.legend(fontsize=11)
        autoscale_y(ax)

    axes[-1].set_xlabel(r'$\ell$', fontsize=13)
    fig.suptitle("CMB Power Spectra — external PPS", fontsize=14)
    fig.tight_layout()
    fig.savefig('./figures/CMB_TT_externalPPS.pdf')
    print("Saved ./figures/CMB_TT_externalPPS.pdf")
