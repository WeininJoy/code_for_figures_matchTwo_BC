#!/usr/bin/env python3
"""
Plot CMB power spectrum from CLASS .dat files
This script reads the output files generated by the C executable and plots them.
"""

import numpy as np
import matplotlib.pyplot as plt
import time
import os # For checking if files exist

# Load Planck spectrum data
# Files downloaded from https://cmb.wintherscoming.no/data/
data_folder = './PlanckData_2018/'
planck_files = {
    'TT': data_folder + 'COM_PowerSpect_CMB-TT-full_R3.01.txt',
    'EE': data_folder + 'COM_PowerSpect_CMB-EE-full_R3.01.txt',
    'TE': data_folder + 'COM_PowerSpect_CMB-TE-full_R3.01.txt'
}
planck_lensing_file = data_folder + 'Planck2018_Lensing.dat'


def load_planck_lensing_data():
    """
    Load Planck 2018 lensing power spectrum.

    File columns: l_min  l_center  l_max  power  sigma_power
    where power = 10^7 * [l(l+1)]^2 * C_l^phiphi / (2pi)

    Returns:
        l_center (np.array): bin-centre multipoles
        power    (np.array): lensing power in Planck units
        sigma    (np.array): 1-sigma errors
    """
    empty = np.array([]), np.array([]), np.array([])
    if not os.path.exists(planck_lensing_file):
        print(f"WARNING: Planck lensing file not found: '{planck_lensing_file}'")
        return empty
    try:
        d = np.loadtxt(planck_lensing_file, comments='#', usecols=(1, 3, 4))
        return d[:, 0], d[:, 1], d[:, 2]
    except Exception as e:
        print(f"Error loading Planck lensing data: {e}")
        return empty


def load_planck_data(spec='TT'):
    """
    Load Planck 2018 power spectrum data for TT.

    Returns:
        l      (np.array): multipole values
        Dl     (np.array): D_l [μK²]
        err    (np.array): shape (2, N) — [negative, positive] errors
    """
    filepath = planck_files[spec]
    empty = np.array([]), np.array([]), np.array([np.array([]), np.array([])])

    if not os.path.exists(filepath):
        print(f"WARNING: Planck {spec} file not found: '{filepath}'")
        return empty

    try:
        d = np.loadtxt(filepath, comments='#', usecols=(0, 1, 2, 3))
        return d[:, 0], d[:, 1], np.array([d[:, 2], d[:, 3]])
    except Exception as e:
        print(f"Error loading Planck {spec} data: {e}")
        return empty


def read_class_cl_file(filename):
    """
    Read CLASS Cl output file.
    CLASS columns: 1:l  2:TT  3:EE  4:TE  5:BB  6:phiphi  ...
    All already in l(l+1)/(2pi)*C_l (dimensionless).

    Returns l, cl_tt, cl_ee, cl_te, cl_pp.
    """
    data = np.loadtxt(filename, comments='#')
    l     = data[:, 0].astype(int)
    cl_tt = data[:, 1]
    cl_ee = data[:, 2]
    cl_te = data[:, 3]
    cl_pp = data[:, 5]   # lensing potential: l(l+1)/(2pi) * C_l^phiphi
    return l, cl_tt, cl_ee, cl_te, cl_pp


def plot_class_on_axes(axes, filename, label=None, color=None):
    """
    Plot TT, EE, TE, phiphi theory curves from one CLASS output file onto four Axes.

    Parameters:
    axes    : sequence of four Axes (TT, EE, TE, phiphi)
    filename: path to CLASS _cl_lensed.dat file
    label   : legend label
    color   : line colour
    """
    try:
        l, cl_tt, cl_ee, cl_te, cl_pp = read_class_cl_file(filename)

        T_CMB = 2.7255                 # K
        fac   = (1e6 * T_CMB) ** 2    # dimensionless → μK²

        axes[0].plot(l, cl_tt * fac, label=label, color=color, linewidth=1.5)
        # axes[1].plot(l, cl_ee * fac, label=label, color=color, linewidth=1.5)
        # axes[2].plot(l, cl_te * fac, label=label, color=color, linewidth=1.5)

        # Convert CLASS pp [l(l+1)/(2pi) C_l^phiphi] to Planck lensing units
        # [10^7 * l(l+1)^2 * C_l^phiphi / (2pi)] = 1e7 * l*(l+1) * cl_pp
        if len(axes) > 1:
            cl_pp_planck = 1e7 * l * (l + 1) * cl_pp
            axes[1].plot(l, cl_pp_planck, label=label, color=color, linewidth=1.5)

        print(f"Successfully plotted {filename}")

    except Exception as e:
        print(f"Error reading {filename}: {e}")


